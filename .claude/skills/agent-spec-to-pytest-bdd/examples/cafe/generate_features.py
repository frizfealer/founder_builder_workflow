"""Write the feature files of slice A from the spec, every step copied from scenarios.md and rules.md.

Usage:
  uv run python generate_features.py           write features/<scenario id>.feature
  uv run python generate_features.py --check   the drift check: exit 1 and name the feature files that
                                               differ, and what of data.json no longer agrees with the spec

A scenario's first World line is the starting situation (Given), the rest are When/And, and each
rule the scenario cites becomes "Then rule <id> holds: <title from rules.md>".
"""
import sys

from harness.data import HERE, rule_titles, scenario, spec_dir

SCENARIOS = ["SC-08", "SC-12", "SC-10"]
FEATURES = HERE / "features"


def feature_text(sc_id):
    sc = scenario(sc_id)
    title = sc_heading(sc_id)
    first, *rest = sc["world"]
    titles = rule_titles()
    lines = ["# Generated by generate_features.py from the café spec's scenarios.md and rules.md. Do not edit.",
             f"Feature: {title}", "", f"  Scenario: {title}", f"    Given {first}"]
    lines += [f"    {'When' if i == 0 else 'And'} {step}" for i, step in enumerate(rest)]
    lines += [f"    {'Then' if i == 0 else 'And'} rule {r} holds: {titles[r]}" for i, r in enumerate(sc["rules"])]
    return "\n".join(lines) + "\n"


def sc_heading(sc_id):
    """'SC-08 Table held and booked': the scenario's heading line in scenarios.md."""
    for line in (spec_dir() / "scenarios.md").read_text(encoding="utf-8").splitlines():
        if line.startswith(f"## {sc_id} "):
            return line[3:].strip()
    raise KeyError(sc_id)


def expected():
    return {FEATURES / f"{sc}.feature": feature_text(sc) for sc in SCENARIOS}


def drift():
    """Feature files that differ from what the spec gives now, or are missing or extra."""
    want = expected()
    have = set(FEATURES.glob("*.feature"))
    differ = [p for p, text in want.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    return sorted(differ + [p for p in have if p not in want])


def main():
    if "--check" in sys.argv[1:]:
        from harness import datacheck
        bad = drift()
        for p in bad:
            print(f"differs from the spec: {p.relative_to(HERE)}")
        print("feature files equal the script's output" if not bad else f"{len(bad)} feature files differ")
        stale = datacheck.problems()
        for s in stale:
            print(f"data.json: {s}")
        print("data.json agrees with the spec" if not stale else f"{len(stale)} data.json problems")
        sys.exit(1 if bad or stale else 0)
    FEATURES.mkdir(exist_ok=True)
    for path, text in expected().items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(HERE)}")


if __name__ == "__main__":
    main()
